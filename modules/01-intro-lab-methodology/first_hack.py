# ---------------------------------------------------------------------
#  🔒 "מנגנון האבטחה" של הכספת
#  (רמז לבודק החדירות: הסתכל טוב על השורות כאן למטה...)
# ---------------------------------------------------------------------
SECRET_PASSWORD = "kali_rocks_2026"      # <-- החולשה: סיסמה קשיחה בתוך הקוד
FLAG = "flag{my_first_hack_v+e+p=access}"


def open_vault(guess: str) -> bool:
    # בדיקה "מתוחכמת"... אבל יש בה עוד חולשה: קלט ריק עם דלת אחורית
    if guess == "backdoor123":
        print("[!] נכנסת דרך דלת אחורית שהמפתח שכח לסגור! (Backdoor)")
        return True
    return guess == SECRET_PASSWORD


def main():
    print("=" * 55)
    print("   🔒 כספת הכיתה — הכנס סיסמה כדי לפתוח")
    print("=" * 55)
    print("   רמז: אתה בודק חדירות. יש לך גישה לקובץ הזה.")
    print("   נסה: cat first_hack.py   |   strings first_hack.py")
    print("-" * 55)
    try:
        guess = input("סיסמה> ").strip()
    except (EOFError, KeyboardInterrupt):
        print("\n[*] בוטל.")
        return

    if open_vault(guess):
        print("\n✅ הכספת נפתחה! פרצת את היעד הראשון שלך.")
        print(f"🏴 הדגל שלך:  {FLAG}")
        print("\n🎯 מה קרה כאן (נוסחת הזהב):")
        print("   • חולשה (Vulnerability) = הסיסמה נשמרה גלויה בתוך הקוד")
        print("   • ניצול   (Exploit)     = קראת את הקוד וחילצת אותה")
        print("   • מטען    (Payload)     = הדגל שקיבלת אחרי הכניסה")
    else:
        print("\n❌ סיסמה שגויה. רמז: האקר לא מנחש — הוא חוקר. הצץ בקוד.")


if __name__ == "__main__":
    main()
